/**
 * Refresh product images + prices from Rainforest API (Amazon data).
 * Run: node scripts/refresh-product-images.mjs
 *
 * Uses 1 API request per product (50 total).
 * Saves results back to lib/products-data.json and regenerates lib/products.ts
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DATA_PATH = path.join(__dirname, '../lib/products-data.json');
const TS_PATH   = path.join(__dirname, '../lib/products.ts');

const API_KEY = '2EDC26B05EC444EF8F2B2A5E4D6F1812';
const DELAY_MS = 1200; // stay well under rate limits

const sleep = ms => new Promise(r => setTimeout(r, ms));

async function fetchProduct(asin) {
  const url = `https://api.rainforestapi.com/request?api_key=${API_KEY}&type=product&asin=${asin}&amazon_domain=amazon.com&include_summarization_attributes=false`;
  const res = await fetch(url);
  if (!res.ok) {
    console.warn(`  ⚠️  HTTP ${res.status} for ${asin}`);
    return null;
  }
  const data = await res.json();
  if (data.request_info && !data.request_info.success) {
    console.warn(`  ⚠️  API error for ${asin}:`, data.request_info.message);
    return null;
  }
  return data.product ?? null;
}

function bestImageUrl(product) {
  // Prefer the largest variant of the main image
  const main = product.main_image?.link ?? '';
  if (main) {
    // Swap any size suffix for _SL1500_ (highest res Amazon supports)
    return main.replace(/\._[A-Z0-9_,]+_\./, '._SL1500_.');
  }
  // Fallback: first image in the gallery
  return product.images?.[0]?.link ?? '';
}

function parsePrice(product) {
  const raw =
    product.buybox_winner?.price?.value ??
    product.price?.value ??
    null;
  if (!raw) return null;
  return { str: `$${Number(raw).toFixed(2)}`, num: Number(raw) };
}

async function main() {
  const products = JSON.parse(fs.readFileSync(DATA_PATH, 'utf8'));
  console.log(`\n🚀 Refreshing ${products.length} products from Rainforest API...\n`);

  let updated = 0;
  let failed  = 0;

  for (let i = 0; i < products.length; i++) {
    const p = products[i];
    process.stdout.write(`[${String(i + 1).padStart(2)}/${products.length}] ${p.asin} — ${p.brand} ... `);

    if (!p.asin) {
      console.log('skipped (no ASIN)');
      continue;
    }

    try {
      const result = await fetchProduct(p.asin);

      if (!result) {
        console.log('❌ no data');
        failed++;
      } else {
        const imgUrl = bestImageUrl(result);
        const price  = parsePrice(result);

        if (imgUrl) p.image_url = imgUrl;
        if (price)  { p.price = price.str; p.price_numeric = price.num; }
        if (result.rating)        p.rating  = result.rating;
        if (result.ratings_total) p.reviews = result.ratings_total;

        console.log(`✅  ${imgUrl ? 'new image' : 'no image'} | ${price ? price.str : 'price unchanged'}`);
        updated++;
      }
    } catch (err) {
      console.log(`❌ error: ${err.message}`);
      failed++;
    }

    // Rate limit — pause between requests
    if (i < products.length - 1) await sleep(DELAY_MS);
  }

  // Save updated JSON
  fs.writeFileSync(DATA_PATH, JSON.stringify(products, null, 2));
  console.log(`\n✅ Saved ${DATA_PATH}`);

  // Regenerate products.ts
  const tsContent = `// Auto-generated by scripts/refresh-product-images.mjs — do not edit manually
// Re-run: node scripts/refresh-product-images.mjs

export type ProductCategory = 'Foods' | 'Herbal' | 'Skincare' | 'Supplements' | 'Accessories';

export interface Product {
  id: string;
  asin: string;
  brand: string;
  name: string;
  category: ProductCategory;
  image_url: string;
  price: string;
  price_numeric: number;
  rating: number;
  reviews: number;
  description: string;
  match_percent: number;
}

export const CATEGORY_META: Record<ProductCategory, { emoji: string; label: string }> = {
  Skincare:    { emoji: '\\u2728',       label: 'Skincare'    },
  Supplements: { emoji: '\\u{1F48A}',   label: 'Supplements' },
  Foods:       { emoji: '\\u{1F957}',   label: 'Foods'       },
  Herbal:      { emoji: '\\u{1F33F}',   label: 'Herbal'      },
  Accessories: { emoji: '\\u{1F6CF}',   label: 'Accessories' },
};

export const PRODUCT_CATEGORIES: Array<'All' | ProductCategory> = [
  'All', 'Skincare', 'Supplements', 'Foods', 'Herbal', 'Accessories',
];

export const PRODUCTS: Product[] = ${JSON.stringify(products, null, 2)};
`;

  fs.writeFileSync(TS_PATH, tsContent);
  console.log(`✅ Saved ${TS_PATH}`);
  console.log(`\n📊 Done — ${updated} updated, ${failed} failed out of ${products.length} products\n`);
}

main().catch(err => { console.error(err); process.exit(1); });
